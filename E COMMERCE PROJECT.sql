--Q96. Find orders where payment value is greater than product value.
WITH order_value AS (
    SELECT
        order_id,
        SUM(price) AS product_value
    FROM orders_item
    GROUP BY order_id
),
payment_value AS (
    SELECT
        order_id,
        SUM(payment_value) AS total_payment
    FROM payment
    GROUP BY order_id
)
SELECT
    ov.order_id,
    ov.product_value,
    pv.total_payment
FROM order_value ov
JOIN payment_value pv
    ON ov.order_id = pv.order_id
WHERE pv.total_payment > ov.product_value
ORDER BY
    pv.total_payment - ov.product_value DESC;
	
