--Q83. Find the top 3 customers in each state.
WITH customer_spending AS (
    SELECT
        c.customer_state,
        c.customer_id,
        SUM(p.payment_value) AS total_spending,
        RANK() OVER (
            PARTITION BY c.customer_state
            ORDER BY SUM(p.payment_value) DESC
        ) AS rnk
    FROM customers c
    JOIN orders o
        ON c.customer_id = o.customer_id
    JOIN payment p
        ON o.order_id = p.order_id
    GROUP BY
        c.customer_state,
        c.customer_id
)
SELECT
    customer_state,
    customer_id,
    total_spending
FROM customer_spending
WHERE rnk <= 3
ORDER BY customer_state, total_spending DESC;


